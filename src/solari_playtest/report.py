def write_html(path: Path, run: dict[str, Any]) -> None:
    e = lambda x: html.escape("" if x is None else str(x))
    meta = run["meta"]
    f = run["findings"]
    tiles = [
        ("findings", str(len(f))),
        ("high", str(sum(1 for x in f if x["severity"] == "high"))),
        ("controls", str(len(run.get("controls", [])))),
        ("sequences", str(run.get("sequences", 0))),
        ("fps", f"{meta.get('fps', 0):.0f}"),
        ("canvas colours", str(meta.get("canvas", {}).get("distinct_colours", "n/a"))),
    ]
    tiles_html = "".join(
        f"<div class=tile><div class=k>{e(k)}</div><div class='v{' bad' if k == 'high' and v != '0' else ''}'>{e(v)}</div></div>"
        for k, v in tiles
    )
    secs = []
    for x in f:
        steps = (
            "".join(
                f"<li>{e(_step_text(s))} <span class=ev>{e(s.get('intent', ''))}</span></li>"
                for s in x["sequence"]
            )
            or "<li>Load the game and wait for the first frame.</li>"
        )
        ev = x.get("evidence", {})
        evl = []
        if "panel" in ev:
            p = ev["panel"]
            evl.append(
                f"<li><code>{e(p['sel'])}</code> rect x={p['x']} y={p['y']} w={p['w']} h={p['h']}</li>"
            )
        if ev.get("reference"):
            evl.append(f"<li>opened alone: w={ev['reference']['w']} h={ev['reference']['h']}</li>")
        if ev.get("measure") and ev["measure"].get("siblings"):
            evl.append(f"<li>siblings: {e(', '.join(ev['measure']['siblings']))}</li>")
        if ev.get("console"):
            evl.append(f"<li>console: {e(' | '.join(str(c)[:140] for c in ev['console'][:4]))}</li>")
        shots = "".join(f"<img src='{e(Path(s).name)}' alt='evidence'>" for s in x.get("screenshots", [])[:2])
        secs.append(
            f"<section><h2><span class='sev {e(x['severity'])}'>{e(x['severity'].upper())}</span>{e(x['title'])}</h2><b>Reproduce</b><ol>{steps}</ol><ul class=ev>{''.join(evl)}</ul>{shots}<p class=hyp><b>Hypothesis</b> {e(x['hypothesis'])}</p><p class=hyp><b>Falsifier</b> {e(x['falsifier'])}</p></section>"
        )
    doc = f"""<!doctype html><html lang=en><head><meta charset=utf-8><meta name=viewport content="width=device-width,initial-scale=1"><title>playtest · {e(meta.get("target"))}</title><style>{CSS}</style></head>
<body><main><header><div class=brand><b>▮ PLAYTEST</b> <b>///</b> REPORT</div><div class=meta>{e(meta.get("time"))} · {e((meta.get("commit") or "n/a")[:10])} · {e(meta.get("viewport"))}</div></header>
<h1>{e(meta.get("target"))} <span>playtest</span></h1><p class=sub>Built in a Solari sandbox, played in a Solari Chrome ({e(meta.get("webgl", {}).get("renderer", "n/a"))}). Replay: {"rrweb link in report.json, presigned for about 15 minutes" if meta.get("replay_url") else "n/a"}</p>
<div class=grid>{tiles_html}</div>{"".join(secs) or "<section><h2>No findings</h2><p class=ev>Every discovered panel stayed usable across all sequences.</p></section>"}
<footer>generated by solari-playtest · {e(time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()))}</footer></main></body></html>"""
    path.write_text(doc, encoding="utf-8")
