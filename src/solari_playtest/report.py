"""Reports: JSON for machines, Markdown for the coding agent, HTML for humans."""

from __future__ import annotations

import html
import json
import time
from pathlib import Path
from typing import Any


def _step_text(step: dict[str, Any]) -> str:
    a = step.get("action", {})
    if "steps" in a:
        return ", then ".join(_step_text({"action": x}) for x in a["steps"])
    if "close_panel" in a:
        return f"close `{a['close_panel']}` with its close button"
    if "key" in a:
        return f"press `{a['key']}`"
    if "click_text" in a:
        return f'click the control labelled "{a["click_text"]}"'
    if "click_sel" in a:
        return f"click `{a['click_sel']}`"
    if "click_xy" in a:
        return f"click at ({a['click_xy'][0]}, {a['click_xy'][1]})"
    return json.dumps(a)


def write_json(path: Path, run: dict[str, Any]) -> None:
    path.write_text(json.dumps(run, indent=2, default=str), encoding="utf-8")


def write_markdown(path: Path, run: dict[str, Any]) -> None:
    f = run["findings"]
    meta = run["meta"]
    lines = [
        f"# Playtest report: {meta.get('target')}",
        "",
        f"Commit `{meta.get('commit') or 'n/a'}` · viewport {meta.get('viewport')} · {meta.get('time')} · Solari session `{(meta.get('browser_session') or '')[-12:]}`",
        f"WebGL: {meta.get('webgl', {}).get('renderer', 'n/a')} · canvas colours {meta.get('canvas', {}).get('distinct_colours', 'n/a')} · {meta.get('fps', 0):.0f} fps",
        f"Controls discovered: {', '.join(c['label'] for c in run.get('controls', [])) or 'none'} · sequences run: {run.get('sequences', 0)}",
        "Replay: "
        + (
            "presigned rrweb link in report.json (valid about 15 minutes)"
            if meta.get("replay_url")
            else "not available"
        ),
        "",
        f"## {len(f)} finding(s)" if f else "## No findings",
        "",
    ]
    if not f:
        lines.append(
            "Every discovered panel stayed usable across all open/close sequences, no console errors, canvas renders."
        )
    for x in f:
        lines += [
            f"### {x['id']} · {x['severity'].upper()} · {x['title']}",
            "",
            "**Reproduce** (from a fresh load, after the start screen):",
            "",
        ]
        for i, s in enumerate(x["sequence"], 1):
            lines.append(f"{i}. {_step_text(s)}  ·  _{s.get('intent', '')}_")
        if not x["sequence"]:
            lines.append("1. Load the game and wait for the first frame.")
        ev = x.get("evidence", {})
        lines += ["", "**Evidence**", ""]
        if "panel" in ev:
            p = ev["panel"]
            lines.append(
                f"- `{p['sel']}` rect: x={p['x']} y={p['y']} w={p['w']} h={p['h']} (open={p['open']}, inside viewport={p['inside']})"
            )
        if ev.get("reference"):
            r = ev["reference"]
            lines.append(f"- same panel opened alone from a clean state: w={r['w']} h={r['h']}")
        if ev.get("measure"):
            m = ev["measure"]
            lines.append(
                f"- computed: display={m.get('display')} flex={m.get('flex')} min-height={m.get('minHeight')} overflow={m.get('overflow')} parent=`{m.get('parent')}`"
            )
            if m.get("siblings"):
                lines.append(f"- siblings in the same container: {', '.join(m['siblings'])}")
        if ev.get("open_panels"):
            lines.append(
                "- open panels at that moment: "
                + "; ".join(f"`{q['sel']}` {q['w']}×{q['h']}" for q in ev["open_panels"])
            )
        if ev.get("console"):
            lines.append("- console: " + " | ".join(str(c)[:160] for c in ev["console"][:5]))
        if ev.get("fps"):
            lines.append(f"- fps {ev['fps']:.0f} on {ev.get('renderer')}")
        for s in x.get("screenshots", []):
            lines.append(f"- screenshot: `{s}`")
        lines += [
            "",
            f"**Hypothesis** {x['hypothesis']}",
            "",
            f"**Falsifier** {x['falsifier']}",
            "",
            "**Verify the fix** re-run the same sequence and check the falsifier holds.",
            "",
        ]
    lines += [
        "",
        "---",
        "",
        "Generated by solari-playtest. The sequences above are deterministic: replay them with `playtest replay <report.json>`.",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


